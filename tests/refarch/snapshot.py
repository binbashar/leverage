"""
Refresh the le-tf-infra-aws snapshot the contract tests run against (tests/test_refarch_contract.py).

The snapshot keeps, verbatim, only the files the CLI reads from a project: build.env, config/common.tfvars
(from its .example), each account's config/*.tfvars, and config.tf/locals.tf/runtime.tf of the layers below,
picked to cover every layout shape the ref-arch uses.

Usage, from the repository root:
    git clone --depth 1 https://github.com/binbashar/le-tf-infra-aws.git /tmp/le-tf-infra-aws
    python tests/refarch/snapshot.py /tmp/le-tf-infra-aws
"""

import shutil
import subprocess
import sys
from pathlib import Path

SNAPSHOT_DIR = Path(__file__).parent / "le-tf-infra-aws"

# One layer per layout shape, plus a full layers group
LAYERS = [
    "apps-devstg/global/cli-test-layer",  # plain layer, global directory
    "apps-devstg/global/base-identities",  # `base-` prefix, dropped from the key
    "apps-devstg/us-east-1/base-tf-backend",  # the backend layer
    "apps-devstg/us-east-1/tools-cloud-nuke",  # `tools-` prefix
    "apps-devstg/us-east-1/k8s-eks-demoapps/cluster",  # layers group
    "apps-devstg/us-east-1/k8s-eks-demoapps/addons",
    "apps-devstg/us-east-1/k8s-eks-demoapps/storage/efs",  # nested layers group
    "apps-devstg/us-east-2/security-keys",  # secondary region, `-dr` key
    "network/us-east-2/base-network",  # secondary region with a `base-` prefix
    "network/us-east-1/client-vpn",  # stale profile, le-tf-infra-aws#1347 (KNOWN_STALE_PROFILES in the tests)
    "shared/global/base-dns/binbash.co",  # layer below a prefixed group
    "shared/us-east-1/tools-vpn-server",  # cross-account profiles
    "management/global/sso",
]
LAYER_FILES = ("config.tf", "locals.tf", "runtime.tf")


def main(refarch_dir: Path) -> None:
    if SNAPSHOT_DIR.exists():
        shutil.rmtree(SNAPSHOT_DIR)

    def copy(source: Path, relative_target: str) -> None:
        target = SNAPSHOT_DIR / relative_target
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)

    copy(refarch_dir / "build.env", "build.env")
    copy(refarch_dir / "config" / "common.tfvars.example", "config/common.tfvars")

    accounts = sorted({layer.split("/")[0] for layer in LAYERS})
    for account in accounts:
        for tfvars in sorted((refarch_dir / account / "config").glob("*.tfvars")):
            copy(tfvars, f"{account}/config/{tfvars.name}")

    for layer in LAYERS:
        if not (refarch_dir / layer / "config.tf").exists():
            sys.exit(f"{layer} has no config.tf in {refarch_dir}: update LAYERS")
        for name in LAYER_FILES:
            if (refarch_dir / layer / name).exists():
                copy(refarch_dir / layer / name, f"{layer}/{name}")

    commit = subprocess.run(
        ["git", "-C", str(refarch_dir), "rev-parse", "HEAD"], capture_output=True, text=True, check=True
    ).stdout.strip()
    (SNAPSHOT_DIR / "SOURCE").write_text(
        f"https://github.com/binbashar/le-tf-infra-aws/tree/{commit}\n"
        "Generated by tests/refarch/snapshot.py; don't edit by hand, rerun it.\n"
    )
    print(f"Snapshot of {commit[:7]}: {len(LAYERS)} layers in {len(accounts)} accounts")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(Path(sys.argv[1]).resolve())
