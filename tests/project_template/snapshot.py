"""
Refresh the snapshot of the project template (le-tf-infra-aws-template) the `project` CLI tests run against
(tests/test_modules/test_project_cli.py), and the golden files of what `project create` makes of it.

The snapshot keeps the two directories the CLI uses from the template repository, verbatim: `template/` and
`le-resources/`.

Usage, from the repository root:
    git clone --depth 1 https://github.com/binbashar/le-tf-infra-aws-template.git /tmp/le-tf-infra-aws-template
    python tests/project_template/snapshot.py /tmp/le-tf-infra-aws-template
    UPDATE_GOLDEN=1 poetry run pytest tests/test_modules/test_project_cli.py

Review the golden files diff before committing it: it is what `project create` now generates.
"""

import shutil
import subprocess
import sys
from pathlib import Path

SNAPSHOT_DIR = Path(__file__).parent / "le-tf-infra-aws-template"
TEMPLATE_DIRECTORIES = ("template", "le-resources")


def main(template_repo: Path) -> None:
    if SNAPSHOT_DIR.exists():
        shutil.rmtree(SNAPSHOT_DIR)

    for directory in TEMPLATE_DIRECTORIES:
        shutil.copytree(template_repo / directory, SNAPSHOT_DIR / directory, symlinks=True)

    commit = subprocess.run(
        ["git", "-C", str(template_repo), "rev-parse", "HEAD"], capture_output=True, text=True, check=True
    ).stdout.strip()
    (SNAPSHOT_DIR / "SOURCE").write_text(
        f"https://github.com/binbashar/le-tf-infra-aws-template/tree/{commit}\n"
        "Generated by tests/project_template/snapshot.py; don't edit by hand, rerun it.\n"
    )
    print(f"Snapshot of {commit[:7]}; now regenerate the golden files (see this script's docstring)")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(Path(sys.argv[1]).resolve())
